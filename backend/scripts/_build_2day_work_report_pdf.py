def git_totals() -> tuple[int, int, int, int]:
    """(commits, files, insertions, deletions) for the window."""
    log = subprocess.run(
        ["git", "log", f"{BASE_COMMIT}..HEAD", "--no-merges", "--shortstat", "--format=tformat:C"],
        cwd=ROOT, capture_output=True, text=True, encoding="utf-8",
    ).stdout
    commits = files = ins = dele = 0
    import re

    for line in log.splitlines():
        line = line.strip()
        if line == "C":
            commits += 1
        elif "changed" in line:
            m = re.search(r"(\d+) file", line)
            files += int(m.group(1)) if m else 0
            m = re.search(r"(\d+) insertion", line)
            ins += int(m.group(1)) if m else 0
            m = re.search(r"(\d+) deletion", line)
            dele += int(m.group(1)) if m else 0
    return commits, files, ins, dele


def table(headers, rows, st, widths):
    """RTL table: logical first column is drawn on the right. widths are fractions in logical order."""
    n = len(headers)
    hv = list(reversed(headers))
    wv = list(reversed(widths))
    usable = A4[0] - 36 * mm
    data = [[Paragraph(wrap(h, st["th"], usable * wv[i] - 12), st["th"]) for i, h in enumerate(hv)]]
    for row in rows:
        cells = []
        for i, cell in enumerate(reversed(row)):
            logical = n - 1 - i
            style = st["tdc"] if widths[logical] <= 0.14 else st["td"]
            cells.append(Paragraph(wrap(str(cell), style, usable * widths[logical] - 12), style))
        data.append(cells)
    t = Table(data, colWidths=[usable * w for w in wv], repeatRows=1)
    t.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), NAVY),
                ("ROWBACKGROUNDS", (0, 1), (-1, -1), [WHITE, ROW_ALT]),
                ("GRID", (0, 0), (-1, -1), 0.4, LINE),
                ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                ("LEFTPADDING", (0, 0), (-1, -1), 5),
                ("RIGHTPADDING", (0, 0), (-1, -1), 5),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ]
        )
    )
    return t


