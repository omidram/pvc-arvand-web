_CTRL = re.compile("[\u202A\u202C\u200F\u200E]")


def _tokens(text: str) -> list[str]:
    """Split on spaces but keep '(...)' groups and 'V 1.17' together."""
    out: list[str] = []
    buf: str | None = None
    for tok in text.split(" "):
        if buf is not None:
            buf += " " + tok
            if buf.count("(") <= buf.count(")") and buf != "V":
                out.append(buf)
                buf = None
            continue
        if tok == "V" or tok.count("(") > tok.count(")"):
            buf = tok
            continue
        out.append(tok)
    if buf is not None:
        out.append(buf)
    return out


def wrap(text: str, style, width: float) -> str:
    """Wrap logically, then bidi-reorder each line (ReportLab cannot wrap RTL text itself)."""
    lines: list[str] = []
    cur = ""
    limit = width * 0.94
    for tok in _tokens(str(text)):
        cand = f"{cur} {tok}" if cur else tok
        if not cur or stringWidth(_CTRL.sub("", fa(cand)), style.fontName, style.fontSize) <= limit:
            cur = cand
        else:
            lines.append(cur)
            cur = tok
    if cur:
        lines.append(cur)
    return "<br/>".join(esc(line) for line in lines)


