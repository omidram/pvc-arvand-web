function lookup(name: string, table: Record<string, string>): string | null {
  if (table[name]) return table[name];
  const key = Object.keys(table).find((k) => k.toLowerCase() === name.toLowerCase());
  return key ? table[key] : null;
}

/** English or Persian title for an Access archive table. Unknown names stay as stored. */
export function archiveTableLabel(name: string, locale: string): string {
  const table = locale === "fa" ? FA : EN;
  return lookup(name, table) || name;
}
