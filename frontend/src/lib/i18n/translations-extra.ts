export type Tree = { [key: string]: string | Tree };

export function deepMerge<T extends Tree>(base: T, extra: Tree): T {
  const out: Tree = { ...base };
  for (const [key, value] of Object.entries(extra)) {
    const current = out[key];
    out[key] = typeof value === "object" && current && typeof current === "object" ? deepMerge(current as Tree, value) : value;
  }
  return out as T;
}

